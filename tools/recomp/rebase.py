"""Move arrays of the retail game to new, larger storage (four players).

    python tools/recomp/rebase.py [--relocs references/TM2-Decomp/config/US/retail_relocs.tsv]

Reads tools/recomp/rebase_arrays.tsv and the decomp's relocation list of the retail
code (docs/RELOCATIONS.md there: every lui/%lo pair and $gp access with the address it
forms), and writes:

- src/rebase.json for recompile.py: per instruction that forms an address in a moved
  array (a %lo or $gp use), the distance it moves ("ea_delta"); recompile.py adds it to
  the address the instruction computes. The lui stays as it is, so a lui shared by
  arrays that move and arrays that don't is fine. And "imm": immediates replaced (loop
  bounds of two players).
- src/runtime/rebase_table.h for the runtime: the new addresses (RB_<name>) and the
  table that copies each array's retail contents to its new place at boot.

Nothing in the game's data points into these arrays (decomp FOUR_HUMANS.md 6), so code
is all there is to change.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = 0x80DE0000  # 64 KB under the port's own areas at 0x80DF0000 (src/vplus/fixes.c)
LIMIT = 0x80DF0000

# Bounds of two players (decomp FOUR_HUMANS.md 2, its port variant's changes):
IMM = {
    0x8011975C: 4,       # uaInit: slti 2 -> 4, ids, reset flags, damageable flag of every record
    0x801198AC: 3 * 0x814,  # carTablesClear: li 0x814 (the last record's offset, counting down)
    0x801558A4: 4,       # viewCreate: refuses i >= 2 -> 4
}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--relocs", default=str(ROOT / "references/TM2-Decomp/config/US/retail_relocs.tsv"))
    ap.add_argument("--arrays", default=str(ROOT / "tools/recomp/rebase_arrays.tsv"))
    ap.add_argument("--identity", action="store_true", help="tests: nothing moves (a build to compare with)")
    args = ap.parse_args()

    arrays = []
    for line in Path(args.arrays).read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#") or line.startswith("name\t"):
            continue
        name, va, size, n, eb = line.split("\t")
        arrays.append({"name": name, "old": int(va, 16), "old_size": int(size, 16), "size": int(n) * int(eb, 16)})
    a = BASE
    for r in arrays:
        assert r["size"] >= r["old_size"], r["name"]
        if args.identity:
            r["new"], r["size"] = r["old"], r["old_size"]
            continue
        r["new"] = a
        a = (a + r["size"] + 15) & ~15
    assert a <= LIMIT, f"{a:08X}"

    def owner(t):
        for r in arrays:
            if r["old"] <= t < r["old"] + r["old_size"]:
                return r
        return None

    ea_delta, rows, kinds = {}, 0, {}
    for line in Path(args.relocs).read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or line.startswith("va\t"):
            continue
        f = line.split("\t")
        va, kind, target = int(f[0], 16), f[1], f[4]
        if kind not in ("lo16", "gprel16") or not target:
            continue
        r = owner(int(target, 16))
        if r is None:
            continue
        if r["new"] != r["old"]:
            ea_delta[f"{va:08X}"] = r["new"] - r["old"]
        rows += 1
        kinds[r["name"]] = kinds.get(r["name"], 0) + 1
    for r in arrays:
        assert kinds.get(r["name"]), f"no code reaches {r['name']}"

    out = {"_": "generated by tools/recomp/rebase.py; do not edit",
           "arrays": [{k: (f"{v:08X}" if isinstance(v, int) and k in ("old", "new") else v) for k, v in r.items()}
                      for r in arrays],
           "ea_delta": dict(sorted(ea_delta.items())),
           "imm": {} if args.identity else {f"{k:08X}": v for k, v in IMM.items()}}
    with open(ROOT / "src/rebase.json", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(out, indent=1) + "\n")

    h = ["/* Generated by tools/recomp/rebase.py from tools/recomp/rebase_arrays.tsv; do not edit.",
         " * The arrays the game uses at a new address (sized for four players).",
         " * Built from the decomp's port variant (its own arrays sized for four, docs/HYBRID.md), each is where",
         " * the address map puts its retail one.",
         " */",
         "#pragma once", "#include <stdint.h>", "",
         "extern const unsigned rc_addrmap_count, rc_view_mode_rows; /* (gen/exe_image.c: the view-mode table's rows) */",
         "uint32_t ga(uint32_t retail);",
         "#define RB_AT(moved, retail) (rc_addrmap_count ? ga(retail) : (moved))",
         "/* the view-mode table's rows the port may use: 16 moved; the decomp's port variant keeps retail's 9 (for",
         " * now: decomp request, docs/DECOMP_REQUESTS.md): no quarter views (four.c) or split-screen mirrors there */",
         "#define RB_VIEW_ROWS (rc_addrmap_count ? rc_view_mode_rows : 16)", ""]
    for r in arrays:
        h.append(f"#define RB_{r['name']} RB_AT(0x{r['new']:08X}u, 0x{r['old']:08X}u)")
    h += ["", "static const struct { uint32_t old, old_size, addr, size; } rb_arrays[] = {"]
    h += [f"    {{0x{r['old']:08X}u, 0x{r['old_size']:X}u, 0x{r['new']:08X}u, 0x{r['size']:X}u}}, /* {r['name']} */"
          for r in arrays]
    h += ["};", f"#define RB_ARRAY_COUNT {len(arrays)}", ""]
    with open(ROOT / "src/runtime/rebase_table.h", "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(h))
    print(f"{len(arrays)} arrays at {BASE:08X}..{a:08X}; {rows} instructions move; "
          + ", ".join(f"{k} {v}" for k, v in kinds.items()))


if __name__ == "__main__":
    main()
